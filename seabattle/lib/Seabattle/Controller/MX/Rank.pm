package Seabattle::Controller::MX::Rank;
use Mojo::Base 'Mojolicious::Controller';
use strict;
use warnings FATAL => 'all';


sub rank {
    my ($self) = @_;

    my @players = map {
        {
            nickname => sprintf("Игрок %02d", $_),
            score    => int(rand(300)),
            rank     => ['Матрос', 'Лейтенант', 'Капитан', 'Адмирал']->[rand(4)],
            position => $_+1
        }
    } 0..7;

    my $result = {
        rating => \@players
    };

    $self->render(json => $result);
}

=head1 НАЗВАНИЕ

Seabattle::Controller::Rank - Контроллер рейтинга игроков для системы Seabattle

=head1 СИНТАКСИС

    use Seabattle::Controller::Rank;

    # Получить текущий рейтинг игроков
    $controller->rank();

=head1 ОПИСАНИЕ

Контроллер предоставляет API для работы с рейтингом игроков. В текущей версии
реализована заглушка, возвращающая тестовые данные.

=head1 МЕТОДЫ

=head2 rank()

Возвращает текущий рейтинг игроков.

Параметры: отсутствуют

Возвращает:
- JSON-структуру с массивом игроков и их характеристиками

Пример ответа:
    {
        "rating": [
            {
                "nickname": "Игрок 01",
                "score": 150,
                "rank": "Капитан",
                "position": 1
            },
            {
                "nickname": "Игрок 02",
                "score": 120,
                "rank": "Лейтенант",
                "position": 2
            }
        ]
    }

Структура данных игрока:
- nickname - Имя игрока
- score - Количество очков
- rank - Звание (Матрос, Лейтенант, Капитан, Адмирал)
- position - Позиция в рейтинге

=head1 ЗАМЕЧАНИЯ

Внимание! В текущей реализации метод возвращает тестовые данные с случайными значениями.
Для рабочей системы потребуется:
1. Реальная база данных игроков
2. Логика расчета рейтинга
3. Система присвоения званий

